// --- MD5, for av_lfg_init's seeding ---------------------------------------------------------------
static void md5_sum(U8 out[16], const U8* in, int len) {
  static const U32 K[64] = {
    0xd76aa478, 0xe8c7b756, 0x242070db, 0xc1bdceee, 0xf57c0faf, 0x4787c62a, 0xa8304613, 0xfd469501,
    0x698098d8, 0x8b44f7af, 0xffff5bb1, 0x895cd7be, 0x6b901122, 0xfd987193, 0xa679438e, 0x49b40821,
    0xf61e2562, 0xc040b340, 0x265e5a51, 0xe9b6c7aa, 0xd62f105d, 0x02441453, 0xd8a1e681, 0xe7d3fbc8,
    0x21e1cde6, 0xc33707d6, 0xf4d50d87, 0x455a14ed, 0xa9e3e905, 0xfcefa3f8, 0x676f02d9, 0x8d2a4c8a,
    0xfffa3942, 0x8771f681, 0x6d9d6122, 0xfde5380c, 0xa4beea44, 0x4bdecfa9, 0xf6bb4b60, 0xbebfbc70,
    0x289b7ec6, 0xeaa127fa, 0xd4ef3085, 0x04881d05, 0xd9d4d039, 0xe6db99e5, 0x1fa27cf8, 0xc4ac5665,
    0xf4292244, 0x432aff97, 0xab9423a7, 0xfc93a039, 0x655b59c3, 0x8f0ccc92, 0xffeff47d, 0x85845dd1,
    0x6fa87e4f, 0xfe2ce6e0, 0xa3014314, 0x4e0811a1, 0xf7537e82, 0xbd3af235, 0x2ad7d2bb, 0xeb86d391};
  static const U8 R[64] = {7, 12, 17, 22, 7, 12, 17, 22, 7, 12, 17, 22, 7, 12, 17, 22, 5, 9,  14, 20, 5, 9,
                           14, 20, 5, 9,  14, 20, 5, 9,  14, 20, 4, 11, 16, 23, 4, 11, 16, 23, 4, 11, 16, 23,
                           4, 11, 16, 23, 6, 10, 15, 21, 6, 10, 15, 21, 6, 10, 15, 21, 6, 10, 15, 21};
  U32 h[4] = {0x67452301, 0xefcdab89, 0x98badcfe, 0x10325476};
  U8 blk[128];
  const int n = len < 56 ? 64 : 128;  // (len < 120 here)
  memset(blk, 0, sizeof blk);
  memcpy(blk, in, len);
  blk[len] = 0x80;
  const U64 bits = (U64)len * 8;
  for (int i = 0; i < 8; i++) blk[n - 8 + i] = (U8)(bits >> (8 * i));
  for (int o = 0; o < n; o += 64) {
    U32 w[16], a = h[0], b = h[1], c = h[2], d = h[3];
    for (int i = 0; i < 16; i++)
      w[i] = blk[o + 4 * i] | (U32)blk[o + 4 * i + 1] << 8 | (U32)blk[o + 4 * i + 2] << 16 | (U32)blk[o + 4 * i + 3] << 24;
    for (int i = 0; i < 64; i++) {
      U32 fn;
      int g;
      if (i < 16) fn = (b & c) | (~b & d), g = i;
      else if (i < 32) fn = (d & b) | (~d & c), g = (5 * i + 1) & 15;
      else if (i < 48) fn = b ^ c ^ d, g = (3 * i + 5) & 15;
      else fn = c ^ (b | ~d), g = (7 * i) & 15;
      const U32 t = d;
      d = c;
      c = b;
      const U32 x = a + fn + K[i] + w[g];
      b = b + ((x << R[i]) | (x >> (32 - R[i])));
      a = t;
    }
    h[0] += a, h[1] += b, h[2] += c, h[3] += d;
  }
  for (int i = 0; i < 16; i++) out[i] = (U8)(h[i >> 2] >> (8 * (i & 3)));
}

// --- av_lfg: the dither's generator ---------------------------------------------------------------
struct Lfg {
  U32 state[64];
  int index;
  void init(U32 seed) {
    U8 tmp[16] = {0};
    for (int i = 8; i < 64; i += 4) {
      tmp[0] = (U8)seed, tmp[1] = (U8)(seed >> 8), tmp[2] = (U8)(seed >> 16), tmp[3] = (U8)(seed >> 24);
      tmp[4] = (U8)i;
      md5_sum(tmp, tmp, 16);
      for (int k = 0; k < 4; k++)
        state[i + k] = tmp[4 * k] | (U32)tmp[4 * k + 1] << 8 | (U32)tmp[4 * k + 2] << 16 | (U32)tmp[4 * k + 3] << 24;
    }
    for (int i = 0; i < 8; i++) state[i] = 0;
    index = 0;
  }
  U32 get() {
    const U32 a = state[index & 63] = state[(index - 24) & 63] + state[(index - 55) & 63];
    index++;
    return a;
  }
};

// --- the KBD window (kbdwin.c, av_bessel_i0) ------------------------------------------------------
static double eval_poly(const double* c, int n, double x) {
  double sum = c[n - 1];
  for (int i = n - 2; i >= 0; --i) {
    sum *= x;
    sum += c[i];
  }
  return sum;
}
static double bessel_i0(double x) {
  static const double p1[] = {-2.2335582639474375249e+15, -5.5050369673018427753e+14, -3.2940087627407749166e+13,
                              -8.4925101247114157499e+11, -1.1912746104985237192e+10, -1.0313066708737980747e+08,
                              -5.9545626019847898221e+05, -2.4125195876041896775e+03, -7.0935347449210549190e+00,
                              -1.5453977791786851041e-02, -2.5172644670688975051e-05, -3.0517226450451067446e-08,
                              -2.6843448573468483278e-11, -1.5982226675653184646e-14, -5.2487866627945699800e-18};
  static const double q1[] = {-2.2335582639474375245e+15, 7.8858692566751002988e+12, -1.2207067397808979846e+10,
                              1.0377081058062166144e+07,  -4.8527560179962773045e+03, 1.0};
  static const double p2[] = {-2.2210262233306573296e-04, 1.3067392038106924055e-02, -4.4700805721174453923e-01,
                              5.5674518371240761397e+00,  -2.3517945679239481621e+01, 3.1611322818701131207e+01,
                              -9.6090021968656180000e+00};
  static const double q2[] = {-5.5194330231005480228e-04, 3.2547697594819615062e-02, -1.1151759188741312645e+00,
                              1.3982595353892851542e+01,  -6.0228002066743340583e+01, 8.5539563258012929600e+01,
                              -3.1446690275135491500e+01, 1.0};
  if (x == 0) return 1.0;
  x = fabs(x);
  if (x <= 15) {
    const double y = x * x;
    return eval_poly(p1, countof(p1), y) / eval_poly(q1, countof(q1), y);
  }
  const double y = 1 / x - 1.0 / 15;
  const double r = eval_poly(p2, countof(p2), y) / eval_poly(q2, countof(q2), y);
  return exp(x) / sqrt(x) * r;
}
static void kbd_window(float* w, float alpha, int n) {
  double sum = 0.0, scale = 0.0, temp[257];
  const double alpha2 = 4 * (alpha * M_PI / n) * (alpha * M_PI / n);
  int i;
  for (i = 0; i <= n / 2; i++) {
    const double tmp = alpha2 * i * (n - i);
    temp[i] = bessel_i0(sqrt(tmp));
    scale += temp[i] * (1 + (i && i < n / 2));
  }
  scale = 1.0 / (scale + 1);
  for (i = 0; i <= n / 2; i++) {
    sum += temp[i];
    w[i] = (float)sqrt(sum * scale);
  }
  for (; i < n; i++) {
    sum += temp[n - i];
    w[i] = (float)sqrt(sum * scale);
  }
}

// --- av_tx's float IMDCT (tx_template.c: the split-radix FFT codelets, ff_tx_mdct_inv) ------------
struct Cpx {
  float re, im;
};
static float tx_tab_8[8 / 4 + 1], tx_tab_16[16 / 4 + 1], tx_tab_32[32 / 4 + 1], tx_tab_64[64 / 4 + 1],
    tx_tab_128[128 / 4 + 1];
static void tx_init_tab(float* tab, int len) {
  const double freq = 2 * M_PI / len;
  for (int i = 0; i < len / 4; i++) tab[i] = (float)cos(i * freq);
  tab[len / 4] = 0;
}
#define BF(x, y, a, b) \
  do {                 \
    x = (a) - (b);     \
    y = (a) + (b);     \
  } while (0)
#define CMUL(dre, dim, are, aim, bre, bim)     \
  do {                                         \
    (dre) = (are) * (bre) - (aim) * (bim);     \
    (dim) = (are) * (bim) + (aim) * (bre);     \
  } while (0)
#define BUTTERFLIES(a0, a1, a2, a3) \
  do {                              \
    r0 = a0.re;                     \
    i0 = a0.im;                     \
    r1 = a1.re;                     \
    i1 = a1.im;                     \
    BF(t3, t5, t5, t1);             \
    BF(a2.re, a0.re, r0, t5);       \
    BF(a3.im, a1.im, i1, t3);       \
    BF(t4, t6, t2, t6);             \
    BF(a3.re, a1.re, r1, t4);       \
    BF(a2.im, a0.im, i0, t6);       \
  } while (0)
#define TRANSFORM(a0, a1, a2, a3, wre, wim)    \
  do {                                         \
    CMUL(t1, t2, a2.re, a2.im, wre, -wim);     \
    CMUL(t5, t6, a3.re, a3.im, wre, wim);      \
    BUTTERFLIES(a0, a1, a2, a3);               \
  } while (0)
static void tx_sr_combine(Cpx* z, const float* cos, int len) {
  const int o1 = 2 * len, o2 = 4 * len, o3 = 6 * len;
  const float* wim = cos + o1 - 7;
  float t1, t2, t3, t4, t5, t6, r0, i0, r1, i1;
  for (int i = 0; i < len; i += 4) {
    TRANSFORM(z[0], z[o1 + 0], z[o2 + 0], z[o3 + 0], cos[0], wim[7]);
    TRANSFORM(z[2], z[o1 + 2], z[o2 + 2], z[o3 + 2], cos[2], wim[5]);
    TRANSFORM(z[4], z[o1 + 4], z[o2 + 4], z[o3 + 4], cos[4], wim[3]);
    TRANSFORM(z[6], z[o1 + 6], z[o2 + 6], z[o3 + 6], cos[6], wim[1]);
    TRANSFORM(z[1], z[o1 + 1], z[o2 + 1], z[o3 + 1], cos[1], wim[6]);
    TRANSFORM(z[3], z[o1 + 3], z[o2 + 3], z[o3 + 3], cos[3], wim[4]);
    TRANSFORM(z[5], z[o1 + 5], z[o2 + 5], z[o3 + 5], cos[5], wim[2]);
    TRANSFORM(z[7], z[o1 + 7], z[o2 + 7], z[o3 + 7], cos[7], wim[0]);
    z += 2 * 4;
    cos += 2 * 4;
    wim -= 2 * 4;
  }
}
static void tx_fft4(Cpx* dst, Cpx* src) {
  float t1, t2, t3, t4, t5, t6, t7, t8;
  BF(t3, t1, src[0].re, src[1].re);
  BF(t8, t6, src[3].re, src[2].re);
  BF(dst[2].re, dst[0].re, t1, t6);
  BF(t4, t2, src[0].im, src[1].im);
  BF(t7, t5, src[2].im, src[3].im);
  BF(dst[3].im, dst[1].im, t4, t8);
  BF(dst[3].re, dst[1].re, t3, t7);
  BF(dst[2].im, dst[0].im, t2, t5);
}
static void tx_fft8(Cpx* dst, Cpx* src) {
  float t1, t2, t3, t4, t5, t6, r0, i0, r1, i1;
  const float cos = tx_tab_8[1];
  tx_fft4(dst, src);
  BF(t1, dst[5].re, src[4].re, -src[5].re);
  BF(t2, dst[5].im, src[4].im, -src[5].im);
  BF(t5, dst[7].re, src[6].re, -src[7].re);
  BF(t6, dst[7].im, src[6].im, -src[7].im);
  BUTTERFLIES(dst[0], dst[2], dst[4], dst[6]);
  TRANSFORM(dst[1], dst[3], dst[5], dst[7], cos, cos);
}
static void tx_fft16(Cpx* dst, Cpx* src) {
  const float* cos = tx_tab_16;
  float t1, t2, t3, t4, t5, t6, r0, i0, r1, i1;
  const float cos_16_1 = cos[1], cos_16_2 = cos[2], cos_16_3 = cos[3];
  tx_fft8(dst + 0, src + 0);
  tx_fft4(dst + 8, src + 8);
  tx_fft4(dst + 12, src + 12);
  t1 = dst[8].re;
  t2 = dst[8].im;
  t5 = dst[12].re;
  t6 = dst[12].im;
  BUTTERFLIES(dst[0], dst[4], dst[8], dst[12]);
  TRANSFORM(dst[2], dst[6], dst[10], dst[14], cos_16_2, cos_16_2);
  TRANSFORM(dst[1], dst[5], dst[9], dst[13], cos_16_1, cos_16_3);
  TRANSFORM(dst[3], dst[7], dst[11], dst[15], cos_16_3, cos_16_1);
}
static void tx_fft32(Cpx* dst, Cpx* src) {
  tx_fft16(dst, src);
  tx_fft8(dst + 16, src + 16);
  tx_fft8(dst + 24, src + 24);
  tx_sr_combine(dst, tx_tab_32, 8 >> 1);
}
static void tx_fft64(Cpx* dst, Cpx* src) {
  tx_fft32(dst, src);
  tx_fft16(dst + 32, src + 32);
  tx_fft16(dst + 48, src + 48);
  tx_sr_combine(dst, tx_tab_64, 16 >> 1);
}
static void tx_fft128(Cpx* dst, Cpx* src) {
  tx_fft64(dst, src);
  tx_fft32(dst + 64, src + 64);
  tx_fft32(dst + 96, src + 96);
  tx_sr_combine(dst, tx_tab_128, 32 >> 1);
}
#undef BUTTERFLIES
#undef TRANSFORM
static int split_radix_permutation(int i, int len, int inv) {
  len >>= 1;
  if (len <= 1) return i & 1;
  if (!(i & len)) return split_radix_permutation(i, len, inv) * 2;
  len >>= 1;
  return split_radix_permutation(i, len, inv) * 4 + 1 - 2 * (!(i & len) ^ inv);
}
// the inverse MDCT of len coefficients to len samples (half: av_tx's, without the redundant half)
struct Imdct {
  int len;
  int map[128];
  Cpx exp[256];
  void init(int n) {
    len = n;
    const int sub = n / 2, len4 = n >> 1;
    for (int i = 0; i < sub; i++) map[i] = -split_radix_permutation(i, sub, 1) & (sub - 1);
    const double theta = 1.0 / 8.0, scale = 1.0;  // (sqrt(|scale|), scale 1)
    for (int i = 0; i < len4; i++) {
      const double alpha = M_PI_2 * (i + theta) / len4;
      exp[len4 + i].re = (float)(cos(alpha) * scale);
      exp[len4 + i].im = (float)(sin(alpha) * scale);
    }
    for (int i = 0; i < len4; i++) exp[i] = exp[len4 + map[i]];
    for (int i = 0; i < sub; i++) map[i] <<= 1;
  }
  void inv(float* dst, const float* src) const {
    Cpx* z = (Cpx*)dst;
    const Cpx* e = exp;
    const int len2 = len >> 1, len4 = len >> 2;
    const float* in1 = src;
    const float* in2 = src + (len2 * 2 - 1);
    for (int i = 0; i < len2; i++) {
      const int k = map[i];
      const Cpx tmp = {in2[-k], in1[k]};
      CMUL(z[i].re, z[i].im, tmp.re, tmp.im, e[i].re, e[i].im);
    }
    if (len == 256) tx_fft128(z, z);
    else tx_fft64(z, z);
    e += len2;
    for (int i = 0; i < len4; i++) {
      const int i0 = len4 + i, i1 = len4 - i - 1;
      const Cpx src1 = {z[i1].im, z[i1].re};
      const Cpx src0 = {z[i0].im, z[i0].re};
      CMUL(z[i1].re, z[i0].im, src1.re, src1.im, e[i1].im, e[i1].re);
      CMUL(z[i0].re, z[i1].im, src0.re, src0.im, e[i0].im, e[i0].re);
    }
  }
};
#undef CMUL
#undef BF
// float_dsp's vector_fmul_window
static void fmul_window(float* dst, const float* src0, const float* src1, const float* win, int len) {
  dst += len;
  win += len;
  src0 += len;
  for (int i = -len, j = len - 1; i < 0; i++, j--) {
    const float s0 = src0[i], s1 = src1[j], wi = win[i], wj = win[j];
    dst[i] = s0 * wj - s1 * wi;
    dst[j] = s0 * wi + s1 * wj;
  }
}

