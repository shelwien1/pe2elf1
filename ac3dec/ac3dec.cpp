static void tables_init(void) {
  crc_init();
  bit_alloc_init();
  for (int i = 0; i < 256; i++) {
    const int v = (i >> 5) - ((i >> 7) << 3) - 5;
    dynrng_tab[i] = powf(2.0f, (float)v) * ((i & 0x1F) | 0x20);
  }
  tx_init_tab(tx_tab_8, 8);
  tx_init_tab(tx_tab_16, 16);
  tx_init_tab(tx_tab_32, 32);
  tx_init_tab(tx_tab_64, 64);
  tx_init_tab(tx_tab_128, 128);
}

// The size of the frame at p (n bytes there), from its header: 0 where it isn't one
static int frame_bytes(const U8* p, size_t n) {
  if (n < 6 || p[0] != 0x0B || p[1] != 0x77) return 0;
  const int bsid = p[5] >> 3;
  if (bsid <= 10) {
    const int fscod = p[4] >> 6, frmsizecod = p[4] & 63;
    if (fscod == 3 || frmsizecod > 37) return 0;
    return frame_size_tab[frmsizecod][fscod] * 2;
  }
  if (bsid > 16) return 0;
  if ((p[2] >> 6) == 3) return 0;                            // strmtyp 3
  if ((p[4] >> 6) == 3 && ((p[4] >> 4) & 3) == 3) return 0;  // fscod2 3
  const int fs = ((((p[2] & 7) << 8) | p[3]) + 1) * 2;
  return fs < 8 ? 0 : fs;
}
// whether the CRCs of the frame (n bytes at p) hold
static int frame_crc_ok(const U8* p, int n) {
  const int bsid = p[5] >> 3;
  if (bsid <= 10) {
    const int words = n / 2, f58 = 2 * ((words >> 1) + (words >> 3));
    return crc16(0, p + 2, f58 - 2) == 0 && crc16(0, p + f58, n - f58) == 0;
  }
  return crc16(0, p + 2, n - 2) == 0;
}

struct Stats {
  U64 frames, superframes, concealed_blocks, concealed_frames, skipped_bytes, skipped_frames, odd;
  U64 samples;
  const char* last_err;
  int warned_layout;
};

// what the stream's samples go to: emit(ctx, channels, n samples, the layout, the rate)
typedef void (*EmitFn)(void* ctx, const float* const* ch, int nch, int n, U64 layout, int rate);

// The decoder of a stream, frame by frame: an independent frame starts a superframe, its dependent
// frames add their channels to it; a superframe ends when the next independent frame comes, and
// its samples go out
struct Stream {
  Decoder dec;
  Frame fr;
  Stats st;
  int have, nblk, srate;  // the superframe under way: its blocks, its rate
  U64 ind_layout;         // its independent frame's channels
  U64 layout;             // its channels
  int nlayout;
  int ext_map[OUT_SLOTS];  // its output channel -> output slot
  U64 out_layout;         // the stream's channels (the first superframe's) and rate
  int out_ch, out_rate;
  int skip_dep;           // the dependent frames of a skipped independent one
  EmitFn emit;
  void* emit_ctx;

  void init(int drc) {
    dec.init(drc);
    memset(&st, 0, sizeof st);
    have = out_ch = skip_dep = 0;
  }

  // the superframe out, in the stream's channels
  void flush() {
    if (!have) return;
    have = 0;
    st.superframes++;
    if (!out_ch) {
      out_layout = layout;
      out_ch = nlayout;
      out_rate = srate;
    }
    const float* chans[64];
    static float zeros[256 * NBLK];
    int c = 0;
    for (int i = 0; i < 64 && c < out_ch; i++) {
      const U64 p = 1ull << i;
      if (!(out_layout & p)) continue;
      const int idx = layout_index(layout, p);
      chans[c++] = idx >= 0 ? dec.outbuf[ext_map[idx]] : zeros;
    }
    if ((layout != out_layout || srate != out_rate) && !st.warned_layout) {
      st.warned_layout = 1;
      fprintf(stderr, "ac3dec: the channels or the rate change mid-stream; the first frame's are kept\n");
    }
    emit(emit_ctx, chans, out_ch, 256 * nblk, out_layout, out_rate);
    st.samples += (U64)256 * nblk;
  }

  // a frame (n bytes at p, PAD zero bytes after them); complete: n is all of it, else it is cut
  // short (concealed, as ffmpeg does)
  void frame(const U8* p, int n, int complete) {
    const int eac3 = (p[5] >> 3) > 10;
    const int dep = eac3 && (p[2] >> 6) == 1, substreamid = eac3 ? (p[2] >> 3) & 7 : 0;
    st.frames++;
    if (dep) {
      if (skip_dep || !have) {
        st.skipped_frames++;
        return;
      }
    } else {
      flush();
      skip_dep = 0;
      if (substreamid) {  // (independent substreams after the first: ffmpeg skips them)
        st.skipped_frames++;
        skip_dep = 1;
        return;
      }
    }
    BitIn io;
    io.init(p, n * 8);
    io.pos = 16;
    struct Cb {
      Decoder* d;
      void block(const Frame& f, const Run& r, int blk) { d->block(f, r, blk); }
    } cb = {&dec};
    Walk<BitIn, Cb> w(io, fr, cb);
    w.begin();
    if (!w.header()) {  // (no channels to conceal with)
      st.skipped_frames++;
      st.last_err = fr.err;
      if (!dep) skip_dep = 1;
      return;
    }
    if (dep && (fr.nblk != nblk || fr.srate != srate)) {  // (ffmpeg: not compatible)
      st.skipped_frames++;
      return;
    }
    dec.frame_start(fr, dep);
    const int ok = complete && w.body();
    if (fr.odd) st.odd++;
    if (!ok && (!complete || fr.err_blk < NBLK)) {
      const int from = complete ? dec.good : 0;
      dec.conceal(fr, from);
      st.concealed_blocks += fr.nblk - from;
      st.concealed_frames++;
      st.last_err = complete ? fr.err : "a frame cut short";
    }
    dec.frame_end(fr);
    if (!dep) {
      have = 1;
      nblk = fr.nblk;
      srate = fr.srate;
      ind_layout = channel_layout_tab[fr.b.acmod] | (fr.lfe ? (U64)CH_LFE : 0);
      layout = ind_layout;
      nlayout = fr.nch;
      for (int i = 0; i < OUT_SLOTS; i++) ext_map[i] = i;
    } else {
      dependent(fr);
      dec.ff_downmixed = 1;  // (ffmpeg's ac3_downmix() after a dependent frame)
    }
  }
  // a dependent frame's channels added to the superframe (ffmpeg's extended channel map)
  void dependent(const Frame& f) {
    const U8* chmap = dec_channel_map[f.b.acmod][f.lfe];
    const int map_size = nfchans_tab[f.b.acmod] + f.lfe;
    const int cm = f.b.chanmape ? f.b.chanmap : 0;
    U64 lay = ind_layout;
    for (int ch = 0; ch < 16; ch++)
      if (cm & (1 << (15 - ch))) lay |= custom_chmap[ch][1];
    if (popcount64(lay) > OUT_SLOTS) return;
    int ext[OUT_SLOTS], extend = 0;
    for (int ch = 0; ch < OUT_SLOTS; ch++) ext[ch] = ch;
    for (int ch = 0; ch < 16; ch++) {
      if (!(cm & (1 << (15 - ch)))) continue;
      if (custom_chmap[ch][0]) {
        const int index = layout_index(lay, custom_chmap[ch][1]);
        if (index < 0 || extend >= map_size) break;
        ext[index] = DEP_OFFSET + chmap[extend++];
      } else {
        for (int i = 0; i < 64; i++) {
          if (!((1ull << i) & custom_chmap[ch][1])) continue;
          const int index = layout_index(lay, 1ull << i);
          if (index < 0 || extend >= map_size) break;
          ext[index] = DEP_OFFSET + chmap[extend++];
        }
      }
    }
    layout = lay;
    nlayout = popcount64(lay);
    for (int i = 0; i < OUT_SLOTS; i++) ext_map[i] = ext[i];
  }
};

// --- WAV ------------------------------------------------------------------------------------------
struct Wav {
  FILE* f;
  int fl, nch, rate, started;
  U64 mask, frames;
  U8* buf;
  size_t room;
  static void put16(U8*& p, U32 v) { *p++ = (U8)v, *p++ = (U8)(v >> 8); }
  static void put32(U8*& p, U32 v) { put16(p, v & 0xFFFF), put16(p, v >> 16); }
  // the header, for data_bytes of samples (0xFFFFFFFF: not known)
  void header(U32 data_bytes) {
    U8 h[80], *p = h;
    const int bps = fl ? 4 : 2, ext = nch > 2 || fl;
    const U32 fmt_len = ext ? 40 : 16;
    memcpy(p, "RIFF", 4), p += 4;
    put32(p, data_bytes == 0xFFFFFFFFu ? 0xFFFFFFFFu : 4 + 8 + fmt_len + 8 + data_bytes);
    memcpy(p, "WAVEfmt ", 8), p += 8;
    put32(p, fmt_len);
    put16(p, ext ? 0xFFFE : 1);
    put16(p, nch);
    put32(p, rate);
    put32(p, rate * nch * bps);
    put16(p, nch * bps);
    put16(p, bps * 8);
    if (ext) {
      static const U8 guid[16] = {1, 0, 0, 0, 0, 0, 0x10, 0, 0x80, 0, 0, 0xAA, 0, 0x38, 0x9B, 0x71};
      put16(p, 22);
      put16(p, bps * 8);
      put32(p, (U32)(mask & 0x3FFFF));  // (WAV's positions: the first 18)
      memcpy(p, guid, 16);
      p[0] = fl ? 3 : 1;  // (KSDATAFORMAT_SUBTYPE_IEEE_FLOAT, _PCM)
      p += 16;
    }
    memcpy(p, "data", 4), p += 4;
    put32(p, data_bytes);
    fwrite(h, 1, (size_t)(p - h), f);
  }
  // the sizes, where the file can be written over
  void finish() {
    if (!started) {
      nch = nch ? nch : 2;
      rate = rate ? rate : 48000;
      header(0);
      return;
    }
    const U64 bytes = frames * nch * (fl ? 4 : 2);
    if (bytes < 0xFFFFFFF0ull && f != stdout && !fseek(f, 0, SEEK_SET)) header((U32)bytes);
  }
};
static void wav_emit(void* ctx, const float* const* ch, int nch, int n, U64 layout, int rate) {
  Wav& w = *(Wav*)ctx;
  if (!w.started) {
    w.started = 1;
    w.nch = nch;
    w.rate = rate;
    w.mask = layout;
    w.header(0xFFFFFFFFu);
  }
  const int bps = w.fl ? 4 : 2;
  const size_t need = (size_t)n * nch * bps;
  if (need > w.room) {
    U8* nb = (U8*)realloc(w.buf, need);
    if (!nb) {
      fprintf(stderr, "ac3dec: out of memory\n");
      exit(5);
    }
    w.buf = nb;
    w.room = need;
  }
  U8* p = w.buf;
  for (int i = 0; i < n; i++)
    for (int c = 0; c < nch; c++) {
      const float v = ch[c][i];
      if (w.fl) {
        U32 u;
        memcpy(&u, &v, 4);
        *p++ = (U8)u, *p++ = (U8)(u >> 8), *p++ = (U8)(u >> 16), *p++ = (U8)(u >> 24);
      } else {
        long s = lrintf(v * (1 << 15));
        s = s < -32768 ? -32768 : s > 32767 ? 32767 : s;
        *p++ = (U8)s, *p++ = (U8)(s >> 8);
      }
    }
  fwrite(w.buf, 1, need, w.f);
  w.frames += (U64)n;
}

// --- the input --------------------------------------------------------------------------------------
static U8* read_all(FILE* f, size_t* n) {
  size_t room = 1 << 20, len = 0;
  U8* b = (U8*)malloc(room + PAD);
  if (!b) return nullptr;
  for (;;) {
    if (len == room) {
      room *= 2;
      U8* nb = (U8*)realloc(b, room + PAD);
      if (!nb) {
        free(b);
        return nullptr;
      }
      b = nb;
    }
    const size_t k = fread(b + len, 1, room - len, f);
    len += k;
    if (!k) break;
  }
  memset(b + len, 0, PAD);
  *n = len;
  return b;
}

static void usage(void) {
  fprintf(stderr,
          "ac3dec - AC-3 and E-AC-3 decoder to WAV\n"
          "Usage: ac3dec [options] input.ac3 output.wav\n"
          "  -f   32-bit float samples (default 16-bit PCM)\n"
          "  -d   no dynamic range control (dynrng)\n"
          "  -x   decode as FFmpeg 6.1 does where it departs from A/52\n"
          "  -q   no statistics\n"
          "input and output can be - for stdin and stdout\n");
}

int main(int argc, char** argv) {
  int fl = 0, drc = 1, quiet = 0, a;
  for (a = 1; a < argc && argv[a][0] == '-' && argv[a][1]; a++) {
    if (!strcmp(argv[a], "-f")) fl = 1;
    else if (!strcmp(argv[a], "-d")) drc = 0;
    else if (!strcmp(argv[a], "-x")) g_ffmpeg = 1;
    else if (!strcmp(argv[a], "-q")) quiet = 1;
    else {
      usage();
      return 1;
    }
  }
  if (a != argc - 2) {
    usage();
    return 1;
  }
#ifdef _WIN32
  _setmode(_fileno(stdin), _O_BINARY);
  _setmode(_fileno(stdout), _O_BINARY);
#endif
  const char *in_name = argv[a], *out_name = argv[a + 1];
  FILE* in = strcmp(in_name, "-") ? fopen(in_name, "rb") : stdin;
  if (!in) {
    fprintf(stderr, "ac3dec: can't open %s\n", in_name);
    return 2;
  }
  size_t len = 0;
  U8* buf = read_all(in, &len);
  if (in != stdin) fclose(in);
  if (!buf) {
    fprintf(stderr, "ac3dec: out of memory\n");
    return 5;
  }
  FILE* out = strcmp(out_name, "-") ? fopen(out_name, "wb") : stdout;
  if (!out) {
    fprintf(stderr, "ac3dec: can't create %s\n", out_name);
    return 3;
  }
  tables_init();
  static Stream s;  // (large)
  s.init(drc);
  static Wav w;
  w.f = out;
  w.fl = fl;
  s.emit = wav_emit;
  s.emit_ctx = &w;
  // the frames: a sync word and a header, where the frame's CRCs hold, or the next frame follows
  // it, or the input ends with it
  static U8 fb[MAX_FRAME + PAD];
  size_t pos = 0;
  while (pos + 6 <= len) {
    const int n = buf[pos] == 0x0B && buf[pos + 1] == 0x77 ? frame_bytes(buf + pos, len - pos) : 0;
    int take = 0, complete = 1;
    if (n) {
      if (pos + n > len) take = 1, complete = 0;  // (the last, cut short)
      else take = pos + n == len || frame_bytes(buf + pos + n, len - pos - n) || frame_crc_ok(buf + pos, n);
    }
    if (!take) {
      pos++;
      s.st.skipped_bytes++;
      continue;
    }
    const int m = complete ? n : (int)(len - pos);
    memcpy(fb, buf + pos, m);
    memset(fb + m, 0, PAD);
    s.frame(fb, m, complete);
    pos += m;
  }
  s.st.skipped_bytes += len - pos;
  s.flush();
  w.finish();
  const int werr = ferror(out) || (out != stdout ? fclose(out) : fflush(out));
  free(buf);
  if (werr) {
    fprintf(stderr, "ac3dec: %s: write error\n", out_name);
    return 3;
  }
  if (!quiet) {
    fprintf(stderr, "%s: %llu frames, %llu superframes, %d Hz, %d channels (mask 0x%llx), %llu samples (%.2f s)", in_name,
            (unsigned long long)s.st.frames, (unsigned long long)s.st.superframes, s.out_rate, s.out_ch,
            (unsigned long long)s.out_layout, (unsigned long long)s.st.samples,
            s.out_rate ? (double)s.st.samples / s.out_rate : 0.0);
    if (s.st.concealed_frames)
      fprintf(stderr, "; %llu frames concealed (%llu blocks; %s)", (unsigned long long)s.st.concealed_frames,
              (unsigned long long)s.st.concealed_blocks, s.st.last_err ? s.st.last_err : "?");
    if (s.st.skipped_frames) fprintf(stderr, "; %llu frames skipped", (unsigned long long)s.st.skipped_frames);
    if (s.st.skipped_bytes) fprintf(stderr, "; %llu bytes skipped", (unsigned long long)s.st.skipped_bytes);
    if (s.st.odd) fprintf(stderr, "; %llu frames with values past the levels", (unsigned long long)s.st.odd);
    fprintf(stderr, "\n");
  }
  return 0;
}
