// ac3dec - AC-3 (Dolby Digital, ATSC A/52) and E-AC-3 (Dolby Digital Plus, A/52 Annex E) decoder
// to WAV.
//
// Usage: ac3dec [options] input.ac3 output.wav
//   -f    32-bit float samples (default: 16-bit PCM)
//   -d    no dynamic range control (dynrng is applied by default, as ffmpeg does)
//   -x    decode as FFmpeg 6.1 does where it departs from A/52 (see below), for comparisons
//   -q    no statistics
// input can be - for stdin, output - for stdout.
//
// What it decodes: AC-3 of bsid 0-10 (bsid 6's alternate bit stream syntax, the 9 and 10 half and
// quarter rate variants), every channel mode (dual mono to 3/2) with or without the LFE; E-AC-3
// (bsid 11-16) with 1, 2, 3 or 6 blocks a frame, spectral extension (SPX), the adaptive hybrid
// transform (AHT: vector quantisation, gain adaptive quantisation), coupling and rematrixing,
// block switching, dependent substreams (7.1 and the like: a dependent substream's channels are
// added to its independent substream's, as its channel map places them), and the syntax of
// transient pre-noise processing and of the converter fields (parsed, not applied: decoders may
// ignore them). Not decoded: enhanced coupling (no sample of it is known; such a block is
// concealed, as below) and E-AC-3's reduced sample rates (24, 22.05, 16 kHz: decoded with the
// bit allocation of AC-3's half rate, which A/52 doesn't say is right). Independent substreams
// other than the first (substreamid > 0) are skipped. Frames are found by their sync word and
// their header, and a frame is taken where it is followed by another (or the end), or its CRC
// holds, so bytes between frames and frames cut short are skipped.
//
// The output is what ffmpeg (6.1) decodes, bit for bit in float with ffmpeg -cpuflags 0 (and -x
// where the two differ, see below), to within the rounding of its SIMD code otherwise: the
// mantissas, coupling and rematrixing in the same fixed point, the same dither (av_lfg's
// generator, seeded as ffmpeg seeds it), its IMDCT (av_tx's split-radix FFT, ported), its KBD
// window and its channel order (WAV's: L R C LFE Ls Rs ...), without downmixing. Damaged blocks
// are concealed as ffmpeg conceals them: the last good block again.
//
// Where it departs from ffmpeg (-x does as ffmpeg does):
//   - AHT's VQ table for hebap 4 (Table E4.4): ffmpeg's lacks its first row, so that index i
//     decodes as row i + 1, and 31 as zeros;
//   - E-AC-3's SNR offsets with snroffststr > 0: ffmpeg reads snroffste in block 0 and not in the
//     blocks after, where Table E1.4 has it implicit in block 0 and sent in the others;
//   - E-AC-3's coupling and SPX banding structures: A/52 takes the default one for the first block
//     of a frame that uses coupling (SPX) and doesn't send one, ffmpeg only for block 0;
//   - AHT is in use for a channel only if exactly one block sends its exponents (nchregs 1);
//     ffmpeg checks only that blocks 1-5 reuse them.
//
// Derived from FFmpeg's AC-3 and E-AC-3 decoder (libavcodec/ac3dec.c, eac3dec.c, ac3.c, ac3tab.c,
// eac3_data.c, kbdwin.c) and libavutil's av_tx, av_lfg and MD5, so this file is licensed under the
// GNU Lesser General Public License, version 2.1 or later.
//
// Build: g++ -O2 -ffp-contract=off -o ac3dec ac3dec.cpp
//        x86_64-w64-mingw32-g++ -O2 -ffp-contract=off -s -static -o ac3dec.exe ac3dec.cpp
// (-ffp-contract=off: no fused multiply-adds, which would round otherwise than ffmpeg's C code.)

