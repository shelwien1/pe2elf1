#!/usr/bin/env bash
# build.sh: assemble dummy.cpp (head.cpp, the accepted .inc files, dummy_init),
# build dummy.so, and convert vbn.exe into vbn.elf with dummy.so injected.
#
# accepted.txt lists the moved functions, callees first; each .inc may name
# the symbol its entry point is patched to with a `// patch: <symbol>` line
# (the __usercall thunks do), the default being __<name>.
set -eu
cd "$(dirname "$0")"
make -s -C .. pe2elf32/pe2elf32 libvbnshim.so

{
  echo '// generated by build.sh -- edit head.cpp, inc/ and accepted.txt instead'
  echo '#include "head.cpp"'
  grep -v '^#' accepted.txt | awk 'NF{print "#include \"inc/" $1 ".inc\""}'
  echo
  echo '__attribute__((constructor)) static void dummy_init()'
  echo '{'
  grep -v '^#' accepted.txt | awk 'NF{print $1}' | while read -r n; do
    va=${n#sub_}
    sym=$(sed -n 's|^// patch: *\([A-Za-z_0-9]*\).*|\1|p' "inc/$n.inc" | head -1)
    echo "  patch_jmp(0x$va, (void *)&${sym:-__$n});"
  done
  echo '}'
} > dummy.cpp

g++ -m32 -O2 -g -std=c++17 -fPIC -shared -mgeneral-regs-only \
    -fpermissive -Wno-narrowing -Wno-write-strings -w \
    -fno-strict-aliasing -U_FORTIFY_SOURCE -D_FORTIFY_SOURCE=0 \
    -Wl,-soname,dummy.so -o dummy.so dummy.cpp
../pe2elf32/pe2elf32 ../vbn.exe vbn.elf --shim-soname libvbnshim.so --inject=dummy.so >/dev/null
cp ../libvbnshim.so .
echo "built dummy.so ($(grep -vc '^#' accepted.txt) functions moved) and vbn.elf"
