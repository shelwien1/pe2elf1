#!/usr/bin/env python3
"""vbn.asm: objdump listing of vbn.exe's code with labels and symbol names.

Each function is disassembled from its own banner address (a linear sweep over
.vbn desynchronises on the zero padding between functions), and every absolute
operand that lands on a symbol from vbn.txt is annotated with its name.
"""
import bisect, os
from common import ROOT, disassemble, load_symbols

syms = sorted((va, kind, name, size or 0) for name, (va, kind, size, _) in load_symbols().items())
starts = [s[0] for s in syms]
funcs = {va: name for va, kind, name, _ in syms if kind == 'F'}


def symname(a):
    i = bisect.bisect_right(starts, a) - 1
    if i < 0:
        return None
    sa, kind, name, size = syms[i]
    if a == sa:
        return name
    if kind in 'DI' and (a < sa + size if size else a - sa < 0x10000):
        return f'{name}+0x{a - sa:x}'
    if kind == 'F' and a - sa < 0x2000:
        return f'{name}+0x{a - sa:x}'
    return None


import re
with open(os.path.join(ROOT, 'vbn.asm'), 'w') as out:
    out.write('; vbn.asm: disassembly of vbn.exe (.vbn code 10000000-1000A08B, .shim thunks 14001000-)\n')
    out.write('; labels from the Hex-Rays banners, data names from vbn.txt (generated by tools/mkasm.py)\n')
    for va, text in disassemble():
        if va in funcs:
            out.write(f'\n{funcs[va]}:\n')
        notes = []
        for h in re.findall(r'0x([0-9a-f]{6,8})', text.split('\t')[-1]):
            s = symname(int(h, 16))
            if s and s not in notes:
                notes.append(s)
        out.write(f'  {va:08x}: {text}' + (f"    ; {', '.join(notes)}" if notes else '') + '\n')
