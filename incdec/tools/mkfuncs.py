#!/usr/bin/env python3
"""funcs.txt: every function body in vbn.exe.c, located by Hex-Rays' own
`//----- (XXXXXXXX) ----` banners rather than by matching definition lines (a
regex over definitions misses every __usercall, whose name is followed by
`@<eax>`, not by `(`).  Columns: VA, name, first and last line, signature."""
import re
from common import ROOT, donor_lines, full_signature
import os

L = donor_lines()
marks = [i for i, l in enumerate(L) if l.startswith('//----- (')]
rows = []
for k, i in enumerate(marks):
    va = int(re.search(r'\(([0-9A-F]+)\)', L[i]).group(1), 16)
    stop = marks[k + 1] if k + 1 < len(marks) else len(L)
    j = i + 1
    while j < stop and (L[j].startswith('//') or not L[j].strip()):
        j += 1
    e = stop - 1
    while e > j and L[e] != '}':
        e -= 1
    sig = full_signature(L, j + 1)
    m = re.search(r'([A-Za-z_]\w*)(@<[^>]*>)?\s*\(', sig)
    rows.append((va, m.group(1) if m else '?', j + 1, e + 1, sig))
with open(os.path.join(ROOT, 'funcs.txt'), 'w') as f:
    f.write('# VA\tname\tfirst line\tlast line\tHex-Rays signature  (generated by tools/mkfuncs.py)\n')
    for va, n, s, e, sig in rows:
        f.write(f'{va:08X}\t{n}\t{s}\t{e}\t{sig}\n')
print(f'{len(rows)} functions')
