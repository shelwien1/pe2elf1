#!/usr/bin/env python3
"""lfefilter.py OUT DUMP... -- dtsdpack's lfefilter.inc: the DTS-HD Master Audio encoders' LFE
filter, as a correction of the decimations of the decoder's interpolation prototype.

The encoders' LFE values are the WAV's LFE channel decimated by 64 by a filter of their own, near
the decoder's 512-tap interpolation prototype (anal.inc's LFE_FIR), then quantized. dtsdpack
decimates by the prototype at twice the LFE's rate (by 32: lfe_decim()), and the encoders' filter
is a fixed combination of those decimations around each value: 27 of them, from 13 before to 13
after (the LFE's own, and those halfway between, where the LFE's rate aliases the filter's band).
It is the least squares fit of the values times their steps on them, each value weighted by 1
over its step squared (what the coder pays for is the error in steps), ridged by 10^-6 of the mean
diagonal.

Each DUMP is a stream's (./mk.sh lfedump): records of the LFE value (32-bit, then 32 bits of
padding), its step and its 27 decimations (64-bit, in 2^-23 of a value times its step: anal.inc's
LFE_Q), native byte order. Written in 2^-30. Needs numpy."""
import sys
import numpy as np

N = 27  # (anal.inc's LFE_N2)


def main():
    if len(sys.argv) < 3:
        sys.exit('usage: lfefilter.py OUT DUMP...')
    out, dumps = sys.argv[1], sys.argv[2:]
    rec = np.dtype([('v', '=i4'), ('pad', '=i4'), ('st', '=i8'), ('f', '=i8', (N,))])
    A = np.zeros((N, N))
    r = np.zeros(N)
    n = 0
    for d in dumps:
        x = np.fromfile(d, dtype=rec)
        x = x[x['st'] > 0]
        X = x['f'].astype(np.float64) / x['st'].astype(np.float64)[:, None]
        A += X.T @ X
        r += X.T @ x['v'].astype(np.float64)
        n += len(x)
    w = np.linalg.solve(A + 1e-6 * np.trace(A) / N * np.eye(N), r)
    q = [int(v) for v in np.round(w * 2 ** 30)]
    rows = ['    ' + ', '.join(str(v) for v in q[i:i + 7]) + ',' for i in range(0, N, 7)]
    with open(out, 'w') as f:
        f.write('// lfefilter.inc -- generated by tools/lfefilter.py from %d LFE values of lossless WAVs\'\n'
                '// streams (./mk.sh lfedump): the DTS-HD Master Audio encoders\' LFE filter, as a correction of\n'
                '// the prototype\'s decimations by 32 around a value (LFE_N2 of them, 13 before to 13 after),\n'
                '// in 2^-30.\n'
                'static const S32 LFE_W2[LFE_N2] = {\n%s\n};\n' % (n, '\n'.join(rows)))


if __name__ == '__main__':
    main()
