#!/usr/bin/env python3
"""pvqblocks.py OUT DUMP... -- dtsdpack's pvqblocks.inc: the first stage of the DTS-HD Master Audio
encoders' ADPCM predictor search, its 64 codewords as learned from their streams' predictors.

The encoders search the ADPCM code book (4096 entries of 4 coefficients) in two stages: the nearest
of 64 codewords of their own, each a block of 64 entries (entries 64 g to 64 g + 63), then the entry
of that block nearest the subband's LPC. The codewords aren't in the decoder's table; they are
found by learning vector quantization (LVQ1) from the predictors of lossless WAVs' streams.

Each DUMP is a stream's (./mk.sh pvqdump): records of the predictor's index (32-bit, then 32 bits
of padding) and the subband's LPC (4 64-bit coefficients in 2^-24, anal.inc's lpc4()), native byte
order. The codewords start as the medians of their blocks' entries; each pass draws up to 100000
predictors of each stream (numpy's default_rng(1)) and, in batches of 256, moves the block of each
predictor whose nearest codeword isn't its block's toward it and the nearest away, by a rate of
0.02, 0.005, then 0.002 (10 passes each). Written in 2^-16 (anal.inc's pvq_block_dist()). Needs
numpy."""
import os, re, sys
import numpy as np

here = os.path.dirname(os.path.abspath(__file__))

def codebook():
    s = open(os.path.join(here, '..', 'tables.inc')).read()
    m = re.search(r'ADPCM_VB\[4096\]\[4\] = \{(.*?)\n\};', s, re.S)
    v = [int(t) for t in re.findall(r'-?\d+', m.group(1))]
    assert len(v) == 4096 * 4
    return np.array(v, dtype=np.float64).reshape(4096, 4) / 8192.0

def load(path):
    raw = open(path, 'rb').read()
    rec = 8 + 8 * 4
    assert len(raw) % rec == 0, path
    n = len(raw) // rec
    v = np.frombuffer(raw, dtype=np.int32).reshape(n, rec // 4)[:, 0].astype(np.int64)
    a = np.frombuffer(raw, dtype=np.int64).reshape(n, rec // 8)[:, 1:].astype(np.float64) / 2 ** 24
    return a, v

def nearest(C, a):
    return ((a[:, None, :] - C[None, :, :]) ** 2).sum(2).argmin(1)

def train(As, ys, VB, epochs=30, per=100000):
    C = np.median(VB.reshape(64, 64, 4), 1)
    rng = np.random.default_rng(1)
    for ep in range(epochs):
        lr = 0.02 if ep < 10 else 0.005 if ep < 20 else 0.002
        idx = [rng.choice(len(y), min(per, len(y)), replace=False) for y in ys]
        A = np.vstack([As[k][idx[k]] for k in range(len(ys))])
        y = np.concatenate([ys[k][idx[k]] for k in range(len(ys))])
        perm = rng.permutation(len(y))
        for s in range(0, len(y), 256):
            i = perm[s:s + 256]
            a, t = A[i], y[i]
            p = nearest(C, a)
            bad = p != t
            if bad.any():
                np.add.at(C, t[bad], lr * (a[bad] - C[t[bad]]))
                np.add.at(C, p[bad], -lr * (a[bad] - C[p[bad]]))
    return C

def main():
    out, dumps = sys.argv[1], sys.argv[2:]
    assert dumps, __doc__
    VB = codebook()
    data = [load(d) for d in dumps]
    C = train([a for a, _ in data], [v // 64 for _, v in data], VB)
    Cq = np.round(C * 65536).astype(np.int64)
    Cr = Cq / 65536.0
    for d, (a, v) in zip(dumps, data):
        blk = nearest(Cr, a)
        e = ((VB.reshape(64, 64, 4)[blk] - a[:, None, :]) ** 2).sum(2).argmin(1)
        full = ((a[:, None, :] - VB[None, :, :]) ** 2).sum(2).argmin(1) if len(v) <= 50000 else None
        print('%s: %d predictors, the block %.2f%% of them, the entry %.2f%%%s' % (
            d, len(v), 100 * np.mean(blk == v // 64), 100 * np.mean(blk * 64 + e == v),
            '' if full is None else ' (the nearest of all %.2f%%)' % (100 * np.mean(full == v))))
    with open(out, 'w') as f:
        f.write('// pvqblocks.inc -- the first stage of the DTS-HD Master Audio encoders\' ADPCM predictor search: the\n'
                '// codewords of its 64 blocks, as learned from their streams (generated by tools/pvqblocks.py;\n'
                '// anal.inc\'s pvq_block_dist()), in 2^-16\n')
        f.write('static const S32 PV_GC[64][4] = {\n')
        for g in range(64):
            f.write('    {' + ', '.join(str(v) for v in Cq[g]) + '},\n')
        f.write('};\n')

main()
