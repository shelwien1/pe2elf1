#!/usr/bin/env python3
"""lfels.py DCADATA_C OUT -- dtsdpack's lfels.inc: FFmpeg's decoder's LFE interpolation undone by
least squares (model_smp.inc's lfe_dec()).

FFmpeg's DTS decoder makes 64 LFE samples of each LFE value (lfe_fir_float_c(), its 64x case): the
64 of value n are the 8 values n, n-1, ..., n-7 (as it dequantized them) through 8 of
ff_dca_lfe_fir_64's coefficients each, and the WAV has them floored to its resolution. So value n
is the least squares solution of the 16 values n to n+15 whose interpolations are the WAV's 1024
samples from value n's on, the 7 values before n known (the ones decoded): a fixed 1024-tap filter
of those samples (LFE_LSH), less a fixed combination of the 7 (LFE_LSU, value n-1 first). Both in
2^-40. DCADATA_C: FFmpeg's libavcodec/dcadata.c. Needs numpy."""
import re
import sys
import numpy as np

N = 16  # (the values solved for: value n and the 15 after it)


def main():
    if len(sys.argv) != 3:
        sys.exit('usage: lfels.py DCADATA_C OUT')
    src = open(sys.argv[1]).read()
    m = re.search(r'ff_dca_lfe_fir_64\)\[256\]\s*=\s*\{(.*?)\};', src, re.S)
    c = np.array([float(v) for v in re.findall(r'-?[0-9.]+(?:e-?\d+)?', m.group(1))], dtype=np.float32)
    c = c.astype(np.float64)
    assert len(c) == 256
    a = np.zeros((64, 8))  # (sample j of a value's 64: tap k's coefficient, value n - k's)
    for j in range(32):
        for k in range(8):
            a[j, k] = c[8 * j + k]
            a[32 + j, k] = c[255 - 8 * j - k]
    mm = np.zeros((64 * N, N))
    for b in range(N):
        for k in range(8):
            if 0 <= b - k < N:
                mm[64 * b:64 * b + 64, b - k] = a[:, k]
    h = mm @ np.linalg.inv(mm.T @ mm)[0]
    u = np.zeros(7)
    for p in range(1, 8):
        for b in range(N):
            if b + p <= 7:
                u[p - 1] += h[64 * b:64 * b + 64] @ a[:, b + p]
    q = 2.0 ** 40
    with open(sys.argv[2], 'w') as o:
        o.write('// lfels.inc -- generated by tools/lfels.py from FFmpeg\'s libavcodec/dcadata.c: its LFE\n'
                '// interpolation (lfe_fir_float_c(), ff_dca_lfe_fir_64) undone by least squares, value n of the\n'
                '// 16 from n whose interpolations are the 1024 samples from value n\'s: LFE_LSH, those samples\'\n'
                '// weights; LFE_LSU, the 7 values before\'s (n-1 first). In 2^-40\n')
        o.write('static const S64 LFE_LSH[%d] = {\n' % (64 * N))
        for i in range(0, 64 * N, 6):
            o.write('    ' + ', '.join('%d' % round(x * q) for x in h[i:i + 6]) + ',\n')
        o.write('};\n')
        o.write('static const S64 LFE_LSU[7] = {' + ', '.join('%d' % round(x * q) for x in u) + '};\n')


main()
