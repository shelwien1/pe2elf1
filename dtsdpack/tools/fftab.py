# fftab.py DCADATA_C OUT -- the tables FFmpeg's DTS encoder (libavcodec/dcaenc.c, 6.1) builds at
# init with libm, computed here the same way (C doubles, this machine's libm through ctypes), as C
# arrays (ffenctab.inc): cos_table, cb_to_level, cb_to_add, band_interpolation and band_spectrum
# (the non-perfect prototype filter's), the masking's MDCT's rotations (not FFmpeg's: to 31 bits,
# where its are a float's), and auf at 32, 44.1 and 48 kHz, clamped at AUF_MIN (where
# clamped, an entry adds nothing to adjust_jnd()'s sums: see the comment written out). DCADATA_C:
# FFmpeg's libavcodec/dcadata.c (its ff_dca_fir_32bands_nonperfect)
import ctypes, re, struct, sys

m = ctypes.CDLL("libm.so.6")
for f in ("cos", "sin", "exp2", "log10", "pow", "exp"):
    getattr(m, f).restype = ctypes.c_double
m.cos.argtypes = m.sin.argtypes = m.exp2.argtypes = m.log10.argtypes = m.exp.argtypes = [ctypes.c_double]
m.pow.argtypes = [ctypes.c_double, ctypes.c_double]
m.llrintf.restype = ctypes.c_longlong
m.llrintf.argtypes = [ctypes.c_float]

M_PI = 3.14159265358979323846
M_PI_2 = 1.57079632679489661923
M_LOG2_10 = 3.32192809488736234787


def f32(x):  # (a double rounded to float, as C converts it)
    return struct.unpack("f", struct.pack("f", x))[0]


def i32(x):  # (int32_t)(double): truncation toward 0
    return int(x)


def exp10(x):
    return m.exp2(M_LOG2_10 * x)


src = open(sys.argv[1]).read()
mt = re.search(r"ff_dca_fir_32bands_nonperfect\)\[512\]\s*=\s*\{(.*?)\};", src, re.S)
fir = [f32(float(v.rstrip("f"))) for v in re.findall(r"[-+0-9.eE]+f?", mt.group(1))]
assert len(fir) == 512

cos_table = [0] * 2048
cos_table[0] = 0x7FFFFFFF
cos_table[512] = 0
cos_table[1024] = -cos_table[0]
for i in range(1, 512):
    cos_table[i] = i32(0x7FFFFFFF * m.cos(M_PI * i / 1024))
    cos_table[1024 - i] = -cos_table[i]
    cos_table[1024 + i] = -cos_table[i]
    cos_table[2048 - i] = cos_table[i]
cb_to_level = [i32(0x7FFFFFFF * exp10(-0.005 * i)) for i in range(2048)]
cb_to_add = [i32(100 * m.log10(1 + exp10(-0.01 * i))) for i in range(256)]
# (0x1000000000ULL times a float: a float product, exact here, then truncated)
band_interp = [i32(f32(float(0x1000000000) * v)) for v in fir]
band_spectrum = []
for j in range(8):
    acc = 0.0
    for i in range(512):
        reconst = fir[i] * (-1 if i & 64 else 1)
        acc += reconst * m.cos(2 * M_PI * (i + 0.5 - 256) * (j + 0.5) / 512)
    band_spectrum.append(i32(200 * m.log10(acc)))
# the MDCT's DCT-IV's rotations (cos, sin of pi (8 m + 1) / 2048, m 0-127: its FFT's are FE_COS's), at
# 2^31, rounded (where FFmpeg's int32 MDCT has them through a float)
mdct_tw = []
for i in range(128):
    a = M_PI * (8 * i + 1) / 2048
    mdct_tw += [min(2**31 - 1, int(round(m.cos(a) * 2147483648.0))), int(round(m.sin(a) * 2147483648.0))]

fc = [50, 150, 250, 350, 450, 570, 700, 840, 1000, 1170, 1370, 1600, 1850, 2150, 2500, 2900, 3400, 4000, 4800,
      5800, 7000, 8500, 10500, 13500, 17000]
erb = [80, 100, 100, 100, 110, 120, 140, 150, 160, 190, 210, 240, 280, 320, 380, 450, 550, 700, 900, 1100, 1300,
       1800, 2500, 3500, 4500]
rates = [32000, 44100, 48000]  # (of FFmpeg's encoder's nine, the three a core is mostly at)


def hom(f):
    f1 = f / 1000
    return (-3.64 * m.pow(f1, -0.8) + 6.8 * m.exp(-0.6 * (f1 - 3.4) * (f1 - 3.4))
            - 6.0 * m.exp(-0.15 * (f1 - 8.7) * (f1 - 8.7)) - 0.0006 * (f1 * f1) * (f1 * f1))


def gammafilter(i, f):
    h = (f - fc[i]) / erb[i]
    h = 1 + h * h
    h = 1 / (h * h)
    return 20 * m.log10(h)


AUF_MIN = -3500
auf = []
for r in rates:
    t = []
    for j in range(25):
        row = []
        for k in range(256):
            freq = r * (k + 0.5) / 512
            row.append(max(AUF_MIN, i32(10 * (hom(freq) + gammafilter(j, freq)))))
        t.append(row)
    auf.append(t)


def arr(name, ty, vals, per=8):
    s = "static const %s %s[%d] = {\n" % (ty, name, len(vals))
    for i in range(0, len(vals), per):
        s += "    " + ", ".join(str(v) for v in vals[i:i + per]) + ",\n"
    return s + "};\n"


with open(sys.argv[2], "w") as o:
    o.write("// ffenctab.inc -- generated by tools/fftab.py from FFmpeg 6.1's libavcodec/dcadata.c: the tables\n"
            "// its DTS encoder (dcaenc.c) builds at init with libm, built the same way (C doubles), so that\n"
            "// they are the same on every machine. FE_AUF's entries clamped at %d: one that low adds nothing\n"
            "// to adjust_jnd()'s sums (each starts at -1114 or -2047 and grows; a term 256 below the sum\n"
            "// leaves it as it is)\n" % AUF_MIN)
    o.write(arr("FE_COS", "S32", cos_table[:513]))
    o.write(arr("FE_CB_LEVEL", "S32", cb_to_level))
    o.write(arr("FE_CB_ADD", "S16", cb_to_add, 16))
    o.write(arr("FE_INTERP", "S32", band_interp))
    o.write(arr("FE_SPECTRUM", "S32", band_spectrum))
    o.write(arr("FE_MDCT_TW", "S32", mdct_tw))
    o.write("static const S16 FE_AUF[3][25][256] = {  // (32, 44.1 and 48 kHz)\n")
    for t in auf:
        o.write("  {\n")
        for row in t:
            o.write("    {" + ", ".join(str(v) for v in row) + "},\n")
        o.write("  },\n")
    o.write("};\n")
