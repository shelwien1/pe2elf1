#!/usr/bin/env python3
"""hfgroups.py OUT DUMP... -- dtsdpack's hfgroups.inc: the HF VQ group the DTS-HD Master Audio
encoders give a vector of 16 samples, as a score learned from their streams' vectors.

Each DUMP is a stream's (./mk.sh hfdump): records of a vector's index and scale factor (32-bit)
and its 16 samples (64-bit, 2^-16 of the decoder's units), native byte order. The score is an
averaged perceptron's over u = 16 x / (sc 2^16), the code book's units: s_g = u . W_g + b_g, the
best group the most. It starts from anal.inc's HF_GC (each group's centroid; group 0's, the
silences', at 0.3 of it), and weighs each stream alike: 16 passes over 200000 vectors of each,
drawn at random (numpy's default_rng(1)), at a rate of 0.01 and then 0.005, the second half's
weights averaged. Written as W (in 512ths) and e (in 2^-18) such that the least of
|u - W_g|^2 + e_g is the score's best (e = -2 b - |W|^2, its least 0). Needs numpy."""
import os, re, sys
import numpy as np

here = os.path.dirname(os.path.abspath(__file__))

def table(path, name, rows, cols):
    s = open(path).read()
    i = s.index(name)
    body = s[s.index('{', i) + 1:s.index('};', i)]
    v = [int(x) for x in re.findall(r'-?\d+', body)]
    assert len(v) == rows * cols, (name, len(v))
    return np.array(v, dtype=np.float64).reshape(rows, cols)

def load(path):
    raw = open(path, 'rb').read()
    rec = 8 + 8 * 16
    assert len(raw) % rec == 0, path
    n = len(raw) // rec
    h = np.frombuffer(raw, dtype=np.int32).reshape(n, rec // 4)[:, :2]
    x = np.frombuffer(raw, dtype=np.int64).reshape(n, rec // 8)[:, 1:]
    v, sc = h[:, 0].astype(np.int64), h[:, 1].astype(np.float64)
    return 16.0 * x.astype(np.float64) / (sc[:, None] * 65536.0), v >> 5

def train(Us, ys, epochs=16, per=200000):
    C = table(os.path.join(here, '..', 'anal.inc'), 'static const S16 HF_GC[32][32]', 32, 32)[:, :16] / 512.0
    C[0] *= 0.3
    W, b = C.copy(), -(C ** 2).sum(1) / 2
    rng = np.random.default_rng(1)
    Wa, ba, na = np.zeros_like(W), np.zeros_like(b), 0
    for ep in range(epochs):
        lr = 0.01 if ep < epochs // 2 else 0.005
        idx = [rng.choice(len(y), per, replace=len(y) < per) for y in ys]
        U = np.vstack([Us[k][idx[k]] for k in range(len(ys))])
        y = np.concatenate([ys[k][idx[k]] for k in range(len(ys))])
        perm = rng.permutation(len(y))
        for s in range(0, len(y), 256):
            i = perm[s:s + 256]
            u, t = U[i], y[i]
            S = u @ W.T + b[None, :]
            st = S[np.arange(len(i)), t]
            S[np.arange(len(i)), t] = -1e18
            p = S.argmax(1)
            bad = st < S[np.arange(len(i)), p]
            if bad.any():
                np.add.at(W, t[bad], lr * u[bad])
                np.add.at(b, t[bad], lr * 64)
                np.add.at(W, p[bad], -lr * u[bad])
                np.add.at(b, p[bad], -lr * 64)
            if ep >= epochs // 2:
                Wa += W
                ba += b
                na += 1
    return Wa / na, ba / na

def main():
    out, dumps = sys.argv[1], sys.argv[2:]
    assert dumps, __doc__
    data = [load(d) for d in dumps]
    W, b = train([u for u, _ in data], [y for _, y in data])
    for d, (u, y) in zip(dumps, data):
        hit = np.mean((u @ W.T + b[None, :]).argmax(1) == y) * 100
        print(f'{d}: {len(y)} vectors, the group {hit:.2f}% of them')
    Wq = np.round(W * 512).astype(np.int64)
    e = -2 * b - ((Wq / 512.0) ** 2).sum(1)
    Eq = np.round((e - e.min()) * 2 ** 18).astype(np.int64)
    with open(out, 'w') as f:
        f.write('// hfgroups.inc -- the HF VQ group the DTS-HD Master Audio encoders give a vector of 16 samples, as\n'
                '// learned from their streams (generated by tools/hfgroups.py; anal.inc\'s hf_group_score())\n')
        f.write('static const S32 HF_GW[32][16] = {\n')
        for g in range(32):
            f.write('    {' + ', '.join(str(v) for v in Wq[g]) + '},\n')
        f.write('};\nstatic const S64 HF_GE[32] = {\n')
        for g in range(0, 32, 8):
            f.write('    ' + ', '.join(str(v) for v in Eq[g:g + 8]) + ',\n')
        f.write('};\n')

main()
