// A lane of an object, by index.  `&(x)` is what makes these work on an
// lvalue of any type -- and what makes them lvalues themselves, which the
// bodies rely on: `LOBYTE(v10) = ...` is a store into byte 0 of `v10`.
#define BYTEn(x, n)   (*((uint8_t  *)&(x) + (n)))
#define WORDn(x, n)   (*((uint16_t *)&(x) + (n)))
#define DWORDn(x, n)  (*((uint32_t *)&(x) + (n)))

// Little-endian only, which this target is: lane 0 is the low one.  defs.h
// wrote these through LOW_IND/HIGH_IND/LAST_IND so that one header could serve
// both byte orders; -m32 x86 is the only target here and the indirection was
// three macros to say `0` and `sizeof(x)/sizeof(lane) - 1`.
#define LOBYTE(x)  BYTEn(x, 0)
#define LOWORD(x)  WORDn(x, 0)
#define LODWORD(x) DWORDn(x, 0)
#define HIBYTE(x)  BYTEn(x,  sizeof(x) - 1)
#define HIWORD(x)  WORDn(x,  sizeof(x) / 2 - 1)
#define HIDWORD(x) DWORDn(x, sizeof(x) / 4 - 1)
#define BYTE1(x)   BYTEn(x, 1)
#define BYTE2(x)   BYTEn(x, 2)
#define BYTE4(x)   BYTEn(x, 4)
#define WORD2(x)   WORDn(x, 2)

// Two 32-bit halves as one 64-bit value, which is how Hex-Rays writes a
// register pair.
#define __PAIR64__(high, low) (((uint64_t)(high) << 32) | (uint32_t)(low))

// |x| as an unsigned value.  The sign of the *result* is the point: the bodies
// store it into a byte, and `abs32(INT32_MIN)` has no signed answer.
inline uint32_t abs32(int32_t x) { return x >= 0 ? (uint32_t)x : (uint32_t)-x; }

// The x86 overflow flag of `x - y`, which `alt_p2_model` reads once to
// reconstruct a signed comparison the compiler had already split into flags.
// defs.h computed it from a `__SETS__` helper over four widths; both operands
// here are `int32_t`, so this is the one width.
inline int8_t __OFSUB__(int32_t x, int32_t y)
{
  int8_t sx = (int8_t)(x < 0);
  return (int8_t)((sx ^ (int8_t)(y < 0)) & (sx ^ (int8_t)((int32_t)(x - y) < 0)));
}

