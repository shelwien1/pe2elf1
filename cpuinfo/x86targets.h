struct Cache { int level, type, kb, ways, line, shared; }; // type: 1 data, 2 instruction, 3 unified

struct Cpu {
  char vendor[13], brand[49], hv[13];
  int vid;                  // V_INTEL ..., V_GENERIC: another
  uint sig, family, model, stepping; // family/model with the extended fields (LLVM's way)
  uint max_leaf, max_ext;
  qword xcr0;
  bool osxsave, hypervisor, hybrid;
  FSet hw;                  // what the CPU has
  FSet f;                   // what can be used: hw, where the OS saves the registers
  FSet cnat, gnat;          // the features as clang's (getHostCPUFeatures) and gcc's
                            // (get_available_features) -march=native read them
  int level;                // x86-64-v level: 0 (not 64-bit), 1 .. 4
  const char* clang;        // clang's -march=native ("generic": no named cpu)
  const char* gcc;          // gcc's -march=native; 0: gcc refuses (Xeon Phi, gcc 15+)
  Cache cache[8]; int ncache;
};

inline int LevelOf( const FSet& s ) {
  static const int v1[] = { F_LM, F_CMOV, F_CX8, F_X87, F_MMX, F_SSE, F_SSE2, -1 };
  static const int v2[] = { F_CX16, F_SAHF, F_POPCNT, F_SSE3, F_SSE41, F_SSE42, F_SSSE3, -1 };
  static const int v3[] = { F_AVX, F_AVX2, F_BMI, F_BMI2, F_F16C, F_FMA, F_LZCNT, F_MOVBE, -1 };
  static const int v4[] = { F_AVX512F, F_AVX512BW, F_AVX512CD, F_AVX512DQ, F_AVX512VL, -1 };
  const int* v[4] = { v1, v2, v3, v4 };
  int l = 0;
  for( ; l<4; l++ ) for( const int* p=v[l]; *p>=0; p++ ) if( !Has( s, *p ) ) return l;
  return l;
}

// drop what lacks what it needs (avx2 where the OS does not save ymm ...)
inline void Consistent( FSet& s ) {
  for( bool ch=true; ch; ) {
    ch = false;
    for( int f=0; f<N_FEAT; f++ ) if( Has( s, f ) && !Empty( Sub( x86_needs[f], s ) ) ) { Set( s, f, false ); ch = true; }
  }
}

// the features: getHostCPUFeatures (LLVM) and get_available_features (GCC)
