struct Cpuid {
  enum { MAXL = 640 };
  Leaf l[MAXL];
  int n;
  qword xcr0;       // XGETBV(0): the register states the OS saves
  int xcr0_set;     // xcr0 was read (or given in the dump)
  void Clear() { n = 0; xcr0 = 0; xcr0_set = 0; }
  void Add( uint leaf, uint sub, const uint r[4] ) {
    for( int i=0; i<n; i++ ) if( (l[i].leaf==leaf) && (l[i].sub==sub) ) { memcpy( l[i].r, r, 16 ); return; }
    if( n>=MAXL ) return;
    l[n].leaf = leaf; l[n].sub = sub; memcpy( l[n].r, r, 16 ); n++;
  }
  // zeros when the leaf is not there
  bool Get( uint leaf, uint sub, uint r[4] ) const {
    for( int i=0; i<n; i++ ) if( (l[i].leaf==leaf) && (l[i].sub==sub) ) { memcpy( r, l[i].r, 16 ); return true; }
    memset( r, 0, 16 ); return false;
  }
  uint R( uint leaf, uint sub, int i ) const { uint r[4]; Get( leaf, sub, r ); return r[i]; }
};

