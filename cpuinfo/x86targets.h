  if( (c.max_leaf>=7) && (r7[0]>=1) ) d.Get( 7, 1, r71 ); else memset( r71, 0, 16 );
  if( c.max_ext>=0x80000001u ) d.Get( 0x80000001u, 0, e1 ); else memset( e1, 0, 16 );
