// deterministic cache parameters: leaf 4 (Intel, Zhaoxin), 8000001Dh (AMD
// with TOPOEXT), else AMD's 80000005h/80000006h
inline void Caches( const Cpuid& d, Cpu& c ) {
  c.ncache = 0;
  uint lf = 0;
  if( ((c.vid==V_AMD) || (c.vid==V_HYGON)) && (c.max_ext>=0x8000001du) && Bit( d.R( 0x80000001u, 0, 2 ), 22 ) ) lf = 0x8000001du;
  else if( (c.vid!=V_AMD) && (c.vid!=V_HYGON) && (c.max_leaf>=4) ) lf = 4;
  if( lf ) {
    for( uint s=0; (s<16) && (c.ncache<8); s++ ) {
      uint r[4];
      if( !d.Get( lf, s, r ) || !(r[0]&31) ) break;
      Cache& k = c.cache[c.ncache++];
      k.type = r[0]&31; k.level = (r[0]>>5)&7; k.shared = ((r[0]>>14)&0xfff)+1;
      k.ways = (r[1]>>22)+1; k.line = (r[1]&0xfff)+1;
      k.kb = int( (qword(k.ways)*(((r[1]>>12)&0x3ff)+1)*k.line*(qword(r[2])+1)) >> 10 );
    }
    if( c.ncache ) return;
  }
  if( c.max_ext>=0x80000005u ) {
    uint r[4]; d.Get( 0x80000005u, 0, r );
    Cache k;
    if( r[2]>>24 ) { k.level = 1; k.type = 1; k.kb = r[2]>>24; k.ways = (r[2]>>16)&0xff; k.line = r[2]&0xff; k.shared = 1; c.cache[c.ncache++] = k; }
    if( r[3]>>24 ) { k.level = 1; k.type = 2; k.kb = r[3]>>24; k.ways = (r[3]>>16)&0xff; k.line = r[3]&0xff; k.shared = 1; c.cache[c.ncache++] = k; }
  }
  if( c.max_ext>=0x80000006u ) {
    uint r[4]; d.Get( 0x80000006u, 0, r );
    Cache k;
    if( r[2]>>16 ) { k.level = 2; k.type = 3; k.kb = r[2]>>16; k.ways = 0; k.line = r[2]&0xff; k.shared = 1; c.cache[c.ncache++] = k; }
    if( r[3]>>18 ) { k.level = 3; k.type = 3; k.kb = (r[3]>>18)*512; k.ways = 0; k.line = r[3]&0xff; k.shared = 0; c.cache[c.ncache++] = k; }
  }
}

inline void Analyze( const Cpuid& d, Cpu& c ) {
  memset( &c, 0, sizeof(c) );
  uint r[4];
  d.Get( 0, 0, r );
  c.max_leaf = r[0];
  memcpy( c.vendor, r+1, 4 ); memcpy( c.vendor+4, r+3, 4 ); memcpy( c.vendor+8, r+2, 4 ); c.vendor[12] = 0;
  d.Get( 1, 0, r );
  c.sig = r[0];
  uint fam = (r[0]>>8)&15, m = (r[0]>>4)&15;
  if( (fam==6) || (fam==15) ) { m += ((r[0]>>16)&15)<<4; if( fam==15 ) fam += (r[0]>>20)&0xff; }
  c.family = fam; c.model = m; c.stepping = r[0]&15;
  c.osxsave = Bit( r[2], 27 )!=0;
  c.hypervisor = Bit( r[2], 31 )!=0;
  c.max_ext = d.R( 0x80000000u, 0, 0 );
  if( (c.max_ext<0x80000000u) || (c.max_ext>0x8000ffffu) ) c.max_ext = 0;
  if( !strcmp( c.vendor, "GenuineIntel" ) ) c.vid = V_INTEL;
  else if( !strcmp( c.vendor, "AuthenticAMD" ) ) c.vid = V_AMD;
  else if( !strcmp( c.vendor, "HygonGenuine" ) ) c.vid = V_HYGON;
  else if( !strcmp( c.vendor, "  Shanghai  " ) ) c.vid = V_ZHAOXIN;
  else if( !strcmp( c.vendor, "CentaurHauls" ) ) c.vid = (((r[0]>>8)&15)<7) ? V_CENTAUR : V_ZHAOXIN;
  else c.vid = V_GENERIC;
  if( c.max_ext>=0x80000004u ) {
    for( uint i=0; i<3; i++ ) { d.Get( 0x80000002u+i, 0, r ); memcpy( c.brand+16*i, r, 16 ); }
    c.brand[48] = 0;
    char* s = c.brand; while( *s==' ' ) s++;
    memmove( c.brand, s, strlen(s)+1 );
    for( int i=int(strlen(c.brand))-1; (i>=0) && (c.brand[i]==' '); i-- ) c.brand[i] = 0;
  }
  if( c.hypervisor && d.Get( 0x40000000u, 0, r ) ) { memcpy( c.hv, r+1, 12 ); c.hv[12] = 0; }
  c.xcr0 = d.xcr0;
  c.hybrid = (c.max_leaf>=7) && Bit( d.R( 7, 0, 3 ), 15 );
  Features( d, c, c.hw, c.f );
  NativeSets( d, c );
  c.level = LevelOf( c.f );
  c.clang = ClangName( c );
  c.gcc = GccName( d, c );
  Caches( d, c );
}

//---- targets

inline int FindTarget( const char* name ) {
  for( int t=0; t<N_TARGET; t++ ) if( !strcmp( x86_target[t].name, name ) ) return t;
  return -1;
}

enum { C_GCC = 1, C_CLANG = 2, C_BOTH = 3 };

// a target's features by the compilers chosen (all of those that know it)
inline FSet TargetSet( int t, int comp ) {
  const X86Target& x = x86_target[t];
  FSet s = Zero();
  if( (comp&C_GCC) && (x.flags&T_GCC) ) s = Or( s, x.g );
  if( (comp&C_CLANG) && (x.flags&T_CLANG) ) s = Or( s, x.c );
  return s;
}

inline bool Known( int t, int comp ) {
  return ((comp&C_GCC) && (x86_target[t].flags&T_GCC)) || ((comp&C_CLANG) && (x86_target[t].flags&T_CLANG));
}

// the vector ISA tier, highest first in the ranking
enum { TIER_X87, TIER_MMX, TIER_SSE, TIER_SSE2, TIER_SSE3, TIER_SSSE3, TIER_SSE41, TIER_SSE42, TIER_AVX, TIER_AVX2,
       TIER_AVX512, TIER_APX };
inline int TierOf( const FSet& s ) {
  if( Has( s, F_APXF ) || Has( s, F_AVX10_2 ) ) return TIER_APX;
  if( Has( s, F_AVX512F ) ) return TIER_AVX512;
  if( Has( s, F_AVX2 ) ) return TIER_AVX2;
  if( Has( s, F_AVX ) ) return TIER_AVX;
  if( Has( s, F_SSE42 ) ) return TIER_SSE42;
  if( Has( s, F_SSE41 ) ) return TIER_SSE41;
  if( Has( s, F_SSSE3 ) ) return TIER_SSSE3;
  if( Has( s, F_SSE3 ) ) return TIER_SSE3;
  if( Has( s, F_SSE2 ) ) return TIER_SSE2;
  if( Has( s, F_SSE ) ) return TIER_SSE;
  if( Has( s, F_MMX ) ) return TIER_MMX;
  return TIER_X87;
}
inline const char* TierName( int t ) {
  static const char* n[] = { "x87", "mmx", "sse", "sse2", "sse3", "ssse3", "sse4.1", "sse4.2", "avx", "avx2", "avx512", "apx" };
  return n[t];
}

struct Match {
  int t;          // the target
  int ok;         // 1: code built for it runs here
  FSet need;      // its features (64-bit-only ones left out for a 32-bit build)
  FSet miss;      // need - cpu: class 'C' ones make it unusable; 'I' ones only matter to intrinsics
  int exact;      // it is (the same as) what -march=native names
  int tier, level, same, nfeat, vaff, strict, gyear, gfirst;
};

// all targets the compilers chosen (comp) take for a bits-bit build: usable
// ones first, ranked; returns how many are usable, *nall: how many in m
inline int RankTargets( const Cpu& c, int comp, int bits, bool strict, Match* m, int* nall ) {
  FSet cc = ClassSet( 'C' ), o64 = Only64();
  int ng = 0;
  for( int t=0; t<N_TARGET; t++ ) if( x86_target[t].group>=ng ) ng = x86_target[t].group+1;
  // a group's first name and its year
  int gfirst[N_TARGET], gyear[N_TARGET];
  for( int g=0; g<ng; g++ ) gfirst[g] = -1;
  for( int t=0; t<N_TARGET; t++ ) { int g = x86_target[t].group; if( gfirst[g]<0 ) { gfirst[g] = t; gyear[g] = x86_target[t].year; } }
  // what -march=native names, per compiler
  int nat[2] = { -1, -1 };
  if( (comp&C_GCC) && c.gcc ) nat[0] = FindTarget( c.gcc );
  if( (comp&C_CLANG) && c.clang ) nat[1] = FindTarget( c.clang );
  // a group is ranked as one: its features are those of all its names (by
  // the compilers chosen), it is "same" if any of its names is
  static FSet gneed[N_TARGET];
  int gsame[N_TARGET];
  for( int g=0; g<ng; g++ ) { gneed[g] = Zero(); gsame[g] = 0; }
  for( int t=0; t<N_TARGET; t++ ) {
    const X86Target& x = x86_target[t];
    if( !Known( t, comp ) || ((bits==64) && !(x.flags&T_64)) ) continue;
    gneed[x.group] = Or( gneed[x.group], TargetSet( t, comp ) );
    for( int i=0; i<2; i++ ) if( nat[i]>=0 ) {
      const X86Target& y = x86_target[nat[i]];
      if( (i==1) && (x.model>=0) && (y.model>=0) && (x.model==y.model) && strncmp( x86_model[x.model], "Generic", 7 ) ) gsame[x.group] = 1;
      if( (i==0) && (x.gproc>=0) && (y.gproc>=0) && (x.gproc==y.gproc) && strcmp( x86_gproc[x.gproc], "generic" ) ) gsame[x.group] = 1;
    }
  }
  int n = 0;
  for( int t=0; t<N_TARGET; t++ ) {
    const X86Target& x = x86_target[t];
    if( !Known( t, comp ) || ((bits==64) && !(x.flags&T_64)) ) continue;
    Match& k = m[n++];
    k.t = t;
    k.need = gneed[x.group];
    Set( k.need, F_AVX10_1, false );  // (no instructions of its own: the avx512 set it implies stands for it)
    if( bits==32 ) k.need = Sub( k.need, o64 );
    k.miss = Sub( k.need, c.f );
    k.strict = Empty( k.miss );
    k.ok = strict ? k.strict : Empty( And( k.miss, cc ) );
    k.exact = 0;
    for( int i=0; i<2; i++ ) if( (nat[i]>=0) && (x86_target[nat[i]].group==x.group) ) k.exact = 1;
    k.tier = TierOf( k.need );
    k.level = LevelOf( k.need );
    k.same = gsame[x.group];
    k.nfeat = Count( And( k.need, cc ) );
    int v = x86_target[gfirst[x.group]].vendor;
    k.vaff = (v==V_GENERIC) ? 0 : (v==c.vid) ? 2
           : ((v==V_AMD) && (c.vid==V_HYGON)) || ((v==V_HYGON) && (c.vid==V_AMD))
             || ((v==V_CENTAUR) && (c.vid==V_ZHAOXIN)) || ((v==V_ZHAOXIN) && (c.vid==V_CENTAUR)) ? 1 : 0;
    k.gyear = gyear[x.group]; k.gfirst = gfirst[x.group];
  }
  std::sort( m, m+n, []( const Match& a, const Match& b ) {
    if( a.ok!=b.ok ) return a.ok>b.ok;
    if( !a.ok ) return a.t<b.t;
    if( a.tier!=b.tier ) return a.tier>b.tier;
    if( a.exact!=b.exact ) return a.exact>b.exact;
    if( a.level!=b.level ) return a.level>b.level;
    if( a.same!=b.same ) return a.same>b.same;
    if( a.nfeat!=b.nfeat ) return a.nfeat>b.nfeat;
    if( a.vaff!=b.vaff ) return a.vaff>b.vaff;
    if( a.gyear!=b.gyear ) return a.gyear>b.gyear;
    if( a.strict!=b.strict ) return a.strict>b.strict;
    if( a.gfirst!=b.gfirst ) return a.gfirst<b.gfirst;
    return a.t<b.t;
  } );
  int u = 0;
  while( (u<n) && m[u].ok ) u++;
  if( nall ) *nall = n;
  return u;
}

